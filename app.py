@app.route(
    "/api/soc-analytics",
    methods=["GET"]
)
def soc_analytics_api():

    try:
        incident_columns = _get_table_columns("incidents")
        ioc_columns = _get_table_columns("iocs")
        evidence_columns = _get_table_columns("evidence")

        total_incidents = 0
        critical = 0
        high = 0
        medium = 0
        low = 0

        if incident_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "incidents"')
            ).fetchone()
            total_incidents = int(row[0] or 0)

            if "risk_level" in incident_columns:
                rows = db.session.execute(text("""
                    SELECT risk_level, COUNT(*)
                    FROM incidents
                    GROUP BY risk_level
                """)).fetchall()
                for level, count in rows:
                    level = str(level or "").upper()
                    if level == "CRITICAL": critical = int(count)
                    elif level == "HIGH": high = int(count)
                    elif level == "MEDIUM": medium = int(count)
                    elif level == "LOW": low = int(count)

        total_iocs = 0
        if ioc_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "iocs"')
            ).fetchone()
            total_iocs = int(row[0] or 0)

        total_evidence = 0
        if evidence_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "evidence"')
            ).fetchone()
            total_evidence = int(row[0] or 0)

        risk_total = critical + high + medium + low
        high_risk = critical + high
        risk_rate = round((high_risk / risk_total) * 100, 2) if risk_total else 0

        return jsonify({
            "success": True,
            "system": "CYBERNEXUS Ω",
            "analytics": {
                "total_incidents": total_incidents,
                "risk_distribution": {
                    "critical": critical,
                    "high": high,
                    "medium": medium,
                    "low": low
                },
                "high_risk_incidents": high_risk,
                "high_risk_percentage": risk_rate,
                "total_iocs": total_iocs,
                "total_evidence": total_evidence
            },
            "status": "operational"
        })

    except Exception as error:
        return jsonify({
            "success": False,
            "error": str(error),
            "system": "CYBERNEXUS Ω",
            "status": "degraded"
        }), 500


@app.route(
    "/api/security-report",
    methods=["GET"]
)
def security_report_api():

    try:
        analytics_response = soc_analytics_api()
        if isinstance(analytics_response, tuple):
            return analytics_response

        payload = analytics_response.get_json()
        if not payload or not payload.get("success"):
            return jsonify(payload or {"success": False}), 500

        analytics = payload.get("analytics", {})
        distribution = analytics.get("risk_distribution", {})
        critical = int(distribution.get("critical", 0))
        high = int(distribution.get("high", 0))
        medium = int(distribution.get("medium", 0))
        low = int(distribution.get("low", 0))

        overall = "LOW"
        if critical > 0:
            overall = "CRITICAL"
        elif high > 0:
            overall = "HIGH"
        elif medium > 0:
            overall = "MEDIUM"

        return jsonify({
            "success": True,
            "system": "CYBERNEXUS Ω",
            "report": {
                "title": "CYBERNEXUS Ω Security Operations Report",
                "overall_risk": overall,
                "total_incidents": analytics.get("total_incidents", 0),
                "critical_incidents": critical,
                "high_incidents": high,
                "medium_incidents": medium,
                "low_incidents": low,
                "total_iocs": analytics.get("total_iocs", 0),
                "total_evidence": analytics.get("total_evidence", 0),
                "high_risk_percentage": analytics.get("high_risk_percentage", 0),
                "recommendation": (
                    "Prioritize critical and high-risk incidents for immediate investigation."
                    if (critical + high) > 0
                    else "Continue routine monitoring and incident correlation."
                )
            },
            "status": "operational"
        })

    except Exception as error:
        return jsonify({
            "success": False,
            "error": str(error),
            "system": "CYBERNEXUS Ω",
            "status": "degraded"
        }), 500



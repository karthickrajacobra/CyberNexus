@app.route(
    "/api/incident",
    methods=["POST"]
)
def incident_api():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    url_result = data.get(
        "url_result"
    )

    file_result = data.get(
        "file_result"
    )

    email_result = data.get(
        "email_result"
    )

    if not any([

        url_result,
        file_result,
        email_result

    ]):

        return jsonify({

            "success":
                False,

            "error":
                "At least one security signal is required."

        }), 400

    try:

        result = run_incident_orchestration(

            url_result=
                url_result,

            file_result=
                file_result,

            email_result=
                email_result

        )

        # ====================================================
        # IOC / THREAT INTELLIGENCE INTEGRATION
        # ====================================================

        incident_identifier = None

        if isinstance(result, dict):
            incident_data = (
                result.get("incident")
                or {}
            )

            if isinstance(
                incident_data,
                dict
            ):
                incident_identifier = (
                    incident_data.get(
                        "incident_id"
                    )
                )

            if not incident_identifier:
                incident_identifier = (
                    result.get(
                        "incident_id"
                    )
                )

        # STEP 1: Create the incident row FIRST so IOC records receive
        # the correct database incident primary key.
        database_saved = _persist_incident(result)

        # STEP 2: Store IOCs against THIS incident.
        ioc_result = _persist_iocs(
            url_result=url_result,
            file_result=file_result,
            email_result=email_result,
            incident_id=incident_identifier
        )

        # STEP 3: Calculate IOC threat-intelligence impact.
        ioc_intelligence = _calculate_ioc_risk_intelligence(ioc_result)

        result = _apply_ioc_risk_to_result(
            result,
            ioc_intelligence
        )

        # STEP 4: Store enrichment in the incident payload.
        if isinstance(result, dict):
            result["ioc_intelligence"] = ioc_intelligence
            result["ioc_storage"] = ioc_result

        # STEP 5: Update the SAME incident row with final risk + enrichment.
        database_updated = _update_incident_record(result)

        if isinstance(result, dict):
            result["database"] = {
                "saved": database_saved,
                "updated": database_updated,
                "database_file": "database/cybernexus.db"
            }

        return jsonify(
            result
        )

    except Exception as error:

        return jsonify({

            "success":
                False,

            "error":
                str(error)

        }), 500



def incident_details_api(incident_id):

    incident_id = str(incident_id or "").strip()

    if not incident_id:
        return jsonify({
            "success": False,
            "error": "Incident ID is required."
        }), 400

    try:
        incident_columns = _get_table_columns("incidents")

        if not incident_columns:
            return jsonify({
                "success": False,
                "error": "Incidents table is unavailable."
            }), 500

        selected_columns = [
            column
            for column in (
                "id", "incident_id", "incident_level",
                "risk_level", "risk_score", "correlation_score",
                "signal_count", "high_risk_signal_count",
                "status", "severity", "description",
                "data", "created_at"
            )
            if column in incident_columns
        ]

        if "incident_id" not in selected_columns:
            return jsonify({
                "success": False,
                "error": "Incident ID column is unavailable."
            }), 500

        column_sql = ", ".join(
            '"' + column + '"'
            for column in selected_columns
        )
        order_column = (
            '"id"'
            if "id" in incident_columns
            else 'rowid'
        )

        query = text(
            f"""
            SELECT {column_sql}
            FROM incidents
            WHERE "incident_id" = :incident_id
            ORDER BY {order_column} DESC
            LIMIT 1
            """
        )

        row = db.session.execute(
            query,
            {"incident_id": incident_id}
        ).fetchone()

        if not row:
            return jsonify({
                "success": False,
                "error": "Incident not found.",
                "incident_id": incident_id
            }), 404

        incident = {
            column: row[index]
            for index, column in enumerate(selected_columns)
        }

        payload = incident.get("data")
        if isinstance(payload, str) and payload.strip():
            try:
                payload = json.loads(payload)
            except Exception:
                payload = None
        elif not isinstance(payload, dict):
            payload = None

        unified_risk = {}
        correlation = {}
        ioc_intelligence = {}
        ioc_storage = {}
        graph = {}
        evidence = []

        if isinstance(payload, dict):
            unified_risk = payload.get("unified_risk") or {}
            correlation = payload.get("correlation") or {}
            ioc_intelligence = payload.get("ioc_intelligence") or {}
            ioc_storage = payload.get("ioc_storage") or {}
            graph = payload.get("graph") or {}
            evidence_value = payload.get("evidence")

            if isinstance(evidence_value, list):
                evidence = evidence_value
            elif isinstance(evidence_value, dict):
                evidence = [evidence_value]

            incident_payload = payload.get("incident") or {}
            if isinstance(incident_payload, dict):
                if not graph:
                    graph = incident_payload.get("graph") or {}
                if not evidence:
                    evidence_value = incident_payload.get("evidence")
                    if isinstance(evidence_value, list):
                        evidence = evidence_value
                    elif isinstance(evidence_value, dict):
                        evidence = [evidence_value]

        database_incident_id = incident.get("id")
        ioc_records = []

        if database_incident_id is not None:
            ioc_columns = _get_table_columns("iocs")

            if ioc_columns and "incident_id" in ioc_columns:
                ioc_select = [
                    column
                    for column in (
                        "id", "ioc_type", "value",
                        "confidence", "source", "created_at"
                    )
                    if column in ioc_columns
                ]

                if ioc_select:
                    ioc_column_sql = ", ".join(
                        '"' + column + '"'
                        for column in ioc_select
                    )
                    ioc_order = (
                        '"id"'
                        if "id" in ioc_columns
                        else 'rowid'
                    )
                    ioc_query = text(
                        f"""
                        SELECT {ioc_column_sql}
                        FROM iocs
                        WHERE "incident_id" = :incident_id
                        ORDER BY {ioc_order} DESC
                        """
                    )
                    ioc_rows = db.session.execute(
                        ioc_query,
                        {"incident_id": database_incident_id}
                    ).fetchall()

                    for ioc_row in ioc_rows:
                        ioc_records.append({
                            column: ioc_row[index]
                            for index, column in enumerate(ioc_select)
                        })

        if not ioc_records and isinstance(ioc_storage, dict):
            stored_records = ioc_storage.get("records") or []
            if isinstance(stored_records, list):
                for record in stored_records:
                    if not isinstance(record, dict):
                        continue
                    ioc = record.get("ioc")
                    if isinstance(ioc, dict):
                        ioc_records.append({
                            "ioc_type": record.get("ioc_type") or ioc.get("ioc_type"),
                            "value": record.get("value") or ioc.get("value"),
                            "confidence": ioc.get("confidence"),
                            "source": ioc.get("source")
                        })

        graph_nodes = graph.get("nodes", []) if isinstance(graph, dict) else []
        graph_edges = graph.get("edges", []) if isinstance(graph, dict) else []

        return jsonify({
            "success": True,
            "incident": {
                "incident_id": incident.get("incident_id", incident_id),
                "incident_level": incident.get("incident_level"),
                "risk_level": incident.get("risk_level"),
                "risk_score": incident.get("risk_score"),
                "correlation_score": incident.get("correlation_score"),
                "signal_count": incident.get("signal_count"),
                "high_risk_signal_count": incident.get("high_risk_signal_count"),
                "status": incident.get("status"),
                "severity": incident.get("severity"),
                "description": incident.get("description"),
                "created_at": incident.get("created_at")
            },
            "risk": unified_risk if isinstance(unified_risk, dict) else {},
            "correlation": correlation if isinstance(correlation, dict) else {},
            "ioc_intelligence": ioc_intelligence if isinstance(ioc_intelligence, dict) else {},
            "iocs": {
                "count": len(ioc_records),
                "records": ioc_records
            },
            "evidence": {
                "count": len(evidence),
                "records": evidence
            },
            "graph": {
                "nodes": graph_nodes if isinstance(graph_nodes, list) else [],
                "edges": graph_edges if isinstance(graph_edges, list) else [],
                "node_count": len(graph_nodes) if isinstance(graph_nodes, list) else 0,
                "edge_count": len(graph_edges) if isinstance(graph_edges, list) else 0
            },
            "database": {
                "incident_row_id": database_incident_id
            }
        })

    except Exception as error:
        return jsonify({
            "success": False,
            "error": str(error),
            "incident_id": incident_id
        }), 500



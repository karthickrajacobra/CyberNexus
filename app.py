def _update_incident_record(
    orchestration_result
):
    """Update an existing incident with final IOC enrichment."""

    if not isinstance(orchestration_result, dict):
        return False

    incident = orchestration_result.get("incident") or {}
    if not isinstance(incident, dict):
        incident = {}

    incident_id = (
        incident.get("incident_id")
        or orchestration_result.get("incident_id")
    )

    if not incident_id:
        return False

    unified = orchestration_result.get("unified_risk") or {}
    correlation = orchestration_result.get("correlation") or {}

    values = {
        "incident_level": incident.get("incident_level"),
        "risk_level": unified.get("overall_level") if isinstance(unified, dict) else None,
        "risk_score": unified.get("overall_score") if isinstance(unified, dict) else None,
        "correlation_score": correlation.get("correlation_score") if isinstance(correlation, dict) else incident.get("correlation_score"),
        "signal_count": incident.get("signal_count"),
        "high_risk_signal_count": incident.get("high_risk_signal_count"),
        "status": incident.get("status") or "OPEN",
        "severity": incident.get("incident_level"),
        "description": incident.get("description", "CyberNexus Ω correlated security incident"),
        "data": orchestration_result
    }

    try:
        columns = _get_table_columns("incidents")
        if not columns:
            return False

        assignments = []
        parameters = {"incident_id": incident_id}

        for key, value in values.items():
            if key in columns:
                assignments.append(f'"{key}" = :{key}')
                parameters[key] = _safe_json(value)

        if not assignments:
            return False

        query = text(
            f"""
            UPDATE "incidents"
            SET {", ".join(assignments)}
            WHERE "incident_id" = :incident_id
            """
        )

        db.session.execute(query, parameters)
        db.session.commit()
        return True

    except Exception as error:
        db.session.rollback()
        print("[DATABASE] Incident update warning:", error)
        return False



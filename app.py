@app.route(
    "/api/soc-metrics",
    methods=["GET"]
)
def soc_metrics_api():

    try:
        incident_count = 0
        critical_count = 0
        high_count = 0
        medium_count = 0
        low_count = 0

        incident_columns = _get_table_columns("incidents")

        if incident_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "incidents"')
            ).fetchone()
            incident_count = int(row[0] or 0)

            if "risk_level" in incident_columns:
                rows = db.session.execute(
                    text("""
                        SELECT risk_level, COUNT(*)
                        FROM incidents
                        GROUP BY risk_level
                    """)
                ).fetchall()

                for level, count in rows:
                    level = str(level or "").upper()
                    if level == "CRITICAL":
                        critical_count = int(count)
                    elif level == "HIGH":
                        high_count = int(count)
                    elif level == "MEDIUM":
                        medium_count = int(count)
                    elif level == "LOW":
                        low_count = int(count)

        ioc_count = 0
        ioc_columns = _get_table_columns("iocs")
        if ioc_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "iocs"')
            ).fetchone()
            ioc_count = int(row[0] or 0)

        evidence_count = 0
        evidence_columns = _get_table_columns("evidence")
        if evidence_columns:
            row = db.session.execute(
                text('SELECT COUNT(*) FROM "evidence"')
            ).fetchone()
            evidence_count = int(row[0] or 0)

        recent_incidents = []

        if incident_columns:
            wanted = (
                "incident_id",
                "risk_level",
                "risk_score",
                "incident_level",
                "correlation_score",
                "status"
            )

            select_columns = [
                f'"{column}"'
                for column in wanted
                if column in incident_columns
            ]

            if "id" in incident_columns:
                order_column = '"id"'
            elif "created_at" in incident_columns:
                order_column = '"created_at"'
            else:
                order_column = 'rowid'

            if select_columns:
                query = f"""
                    SELECT {", ".join(select_columns)}
                    FROM incidents
                    ORDER BY {order_column} DESC
                    LIMIT 10
                """

                rows = db.session.execute(text(query)).fetchall()
                selected_names = [
                    column.strip('"')
                    for column in select_columns
                ]

                for row in rows:
                    record = {}
                    for index, name in enumerate(selected_names):
                        value = row[index]
                        if hasattr(value, "isoformat"):
                            value = value.isoformat()
                        record[name] = value
                    recent_incidents.append(record)

        return jsonify({
            "success": True,
            "metrics": {
                "total_incidents": incident_count,
                "critical": critical_count,
                "high": high_count,
                "medium": medium_count,
                "low": low_count,
                "total_iocs": ioc_count,
                "total_evidence": evidence_count
            },
            "recent_incidents": recent_incidents,
            "system": "CYBERNEXUS Ω",
            "status": "operational"
        })

    except Exception as error:
        return jsonify({
            "success": False,
            "error": str(error),
            "system": "CYBERNEXUS Ω",
            "status": "degraded"
        }), 500




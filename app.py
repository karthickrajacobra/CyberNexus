@app.route(
    "/api/ioc",
    methods=["GET", "POST"]
)
def ioc_api():

    if request.method == "GET":

        value = request.args.get(
            "value",
            ""
        ).strip()

        ioc_type = request.args.get(
            "ioc_type"
        )

        try:
            if value:
                record = IOC_DATABASE.get_ioc(
                    ioc_type or "DOMAIN",
                    value
                )

                return jsonify({
                    "success": True,
                    "found": record is not None,
                    "record": record,
                    "count": (
                        1
                        if record
                        else 0
                    )
                })

            records = IOC_DATABASE.search(
                value="",
                ioc_type=ioc_type
            )

            return jsonify({
                "success": True,
                "records": records,
                "count": len(records),
                "total_iocs": IOC_DATABASE.count()
            })

        except Exception as error:

            return jsonify({
                "success": False,
                "error": str(error)
            }), 500

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    url_result = data.get(
        "url_result"
    )

    file_result = data.get(
        "file_result"
    )

    email_result = data.get(
        "email_result"
    )

    text_value = data.get(
        "text"
    )

    incident_id = data.get(
        "incident_id"
    )

    # Direct text input is supported for IOC extraction tests and
    # threat-intelligence ingestion. The existing structured detector
    # result inputs remain fully supported.
    if (
        isinstance(text_value, str)
        and text_value.strip()
        and not any([
            url_result,
            file_result,
            email_result
        ])
    ):
        url_result = text_value.strip()

    try:
        result = _persist_iocs(
            url_result=url_result,
            file_result=file_result,
            email_result=email_result,
            incident_id=incident_id
        )

        return jsonify({
            "success": True,
            "result": result
        })

    except Exception as error:

        return jsonify({
            "success": False,
            "error": str(error)
        }), 500



def _get_table_columns(table_name):
    """
    Read SQLite table columns dynamically.

    This keeps database persistence compatible with the
    existing CyberNexus database schema.
    """

    try:

        result = db.session.execute(
            text(
                f"PRAGMA table_info({table_name})"
            )
        )

        rows = result.fetchall()

        return [
            row[1]
            for row in rows
        ]

    except Exception:

        return []


def _safe_json(value):
    """
    Convert Python objects into JSON strings
    when necessary.
    """

    if value is None:
        return None

    if isinstance(
        value,
        (dict, list, tuple)
    ):

        try:

            return json.dumps(
                value,
                ensure_ascii=False
            )

        except Exception:

            return str(value)

    return value


def _insert_matching_columns(
    table_name,
    values
):
    """
    Insert only values whose column names actually
    exist in the SQLite table.

    This prevents database schema mismatch errors.
    """

    columns = _get_table_columns(
        table_name
    )

    if not columns:
        return False

    insert_values = {}

    for key, value in values.items():

        if key in columns:

            insert_values[key] = (
                _safe_json(value)
            )

    if not insert_values:
        return False

    column_names = ", ".join(
        f'"{column}"'
        for column in insert_values.keys()
    )

    parameter_names = ", ".join(
        f":{column}"
        for column in insert_values.keys()
    )

    query = text(
        f"""
        INSERT INTO "{table_name}"
        ({column_names})
        VALUES
        ({parameter_names})
        """
    )

    db.session.execute(
        query,
        insert_values
    )

    return True


def _persist_incident(
    orchestration_result
):
    """
    Persist an incident generated by the
    Incident Orchestrator into SQLite.
    """

    if not isinstance(
        orchestration_result,
        dict
    ):
        return False

    incident = (
        orchestration_result.get(
            "incident"
        )
        or {}
    )

    if not isinstance(
        incident,
        dict
    ):
        incident = {}

    incident_id = (
        incident.get("incident_id")
        or orchestration_result.get(
            "incident_id"
        )
    )

    if not incident_id:
        return False

    try:

        # Prevent duplicate incident records
        columns = _get_table_columns(
            "incidents"
        )

        if "incident_id" in columns:

            existing = db.session.execute(
                text(
                    """
                    SELECT incident_id
                    FROM incidents
                    WHERE incident_id = :incident_id
                    LIMIT 1
                    """
                ),
                {
                    "incident_id":
                        incident_id
                }
            ).fetchone()

            if existing:

                return True

        unified = (
            orchestration_result.get(
                "unified_risk"
            )
            or {}
        )

        correlation = (
            orchestration_result.get(
                "correlation"
            )
            or {}
        )

        values = {

            "incident_id":
                incident_id,

            "incident_level":
                incident.get(
                    "incident_level"
                ),

            "risk_level":
                (
                    unified.get(
                        "overall_level"
                    )
                    if isinstance(
                        unified,
                        dict
                    )
                    else None
                ),

            "risk_score":
                (
                    unified.get(
                        "overall_score"
                    )
                    if isinstance(
                        unified,
                        dict
                    )
                    else None
                ),

            "correlation_score":
                incident.get(
                    "correlation_score"
                ),

            "signal_count":
                incident.get(
                    "signal_count"
                ),

            "high_risk_signal_count":
                incident.get(
                    "high_risk_signal_count"
                ),

            "status":
                "OPEN",

            "severity":
                incident.get(
                    "incident_level"
                ),

            "description":
                (
                    "CyberNexus Ω correlated "
                    "security incident"
                ),

            "data":
                orchestration_result

        }

        # Add correlation values if available
        if isinstance(
            correlation,
            dict
        ):

            values[
                "correlation_score"
            ] = correlation.get(
                "correlation_score",
                values.get(
                    "correlation_score"
                )
            )

        inserted = _insert_matching_columns(
            "incidents",
            values
        )

        if inserted:

            db.session.commit()

        return inserted

    except Exception as error:

        db.session.rollback()

        print(
            "[DATABASE] Incident persistence warning:",
            error
        )

        return False



def _get_latest_database_incident_id(incident_id=None):
    """
    Resolve the integer SQLite incident primary key required by
    the existing iocs schema.
    """
    try:
        if incident_id:
            row = db.session.execute(
                text(
                    """
                    SELECT id
                    FROM incidents
                    WHERE incident_id = :incident_id
                    ORDER BY id DESC
                    LIMIT 1
                    """
                ),
                {"incident_id": incident_id}
            ).fetchone()

            if row:
                return int(row[0])

        row = db.session.execute(
            text(
                """
                SELECT id
                FROM incidents
                ORDER BY id DESC
                LIMIT 1
                """
            )
        ).fetchone()

        if row:
            return int(row[0])

    except Exception as error:
        print(
            "[IOC] Incident lookup warning:",
            error
        )

    return None


def _normalize_ioc_type(ioc_type):
    value = str(ioc_type or "").strip().upper()

    aliases = {
        "URL": "URL",
        "URI": "URL",
        "DOMAIN": "DOMAIN",
        "HOSTNAME": "DOMAIN",
        "IP": "IP",
        "IPV4": "IP",
        "IPV6": "IP",
        "EMAIL": "EMAIL",
        "EMAIL_ADDRESS": "EMAIL",
        "MD5": "MD5",
        "SHA1": "SHA1",
        "SHA-1": "SHA1",
        "SHA256": "SHA256",
        "SHA-256": "SHA256",
    }

    return aliases.get(value, value)


def _clean_ioc_values(values):
    if values is None:
        return []

    if isinstance(values, str):
        values = [values]

    if not isinstance(values, (list, tuple, set)):
        return []

    cleaned = []

    for value in values:
        value = str(value).strip()

        if value and value not in cleaned:
            cleaned.append(value)

    return cleaned


def _fallback_extract_iocs(text_value):
    """
    Local compatibility extractor used only when the dedicated
    IOC engine cannot be called through its exposed API.
    """
    import re

    text_value = str(text_value or "")

    found = {
        "urls": [],
        "domains": [],
        "ips": [],
        "emails": [],
        "hashes": {
            "md5": [],
            "sha1": [],
            "sha256": []
        }
    }

    url_pattern = re.compile(
        r"https?://[^\s<>'\"`]+",
        re.IGNORECASE
    )

    email_pattern = re.compile(
        r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b",
        re.IGNORECASE
    )

    ipv4_pattern = re.compile(
        r"\b(?:\d{1,3}\.){3}\d{1,3}\b"
    )

    sha256_pattern = re.compile(
        r"\b[a-fA-F0-9]{64}\b"
    )

    sha1_pattern = re.compile(
        r"\b[a-fA-F0-9]{40}\b"
    )

    md5_pattern = re.compile(
        r"\b[a-fA-F0-9]{32}\b"
    )

    domain_pattern = re.compile(
        r"\b(?:[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}"
        r"[a-zA-Z0-9])?\.)+[a-zA-Z]{2,}\b"
    )

    for value in url_pattern.findall(text_value):
        value = value.rstrip(".,;:)]}")
        if value not in found["urls"]:
            found["urls"].append(value)

    for value in email_pattern.findall(text_value):
        if value not in found["emails"]:
            found["emails"].append(value)

    for value in ipv4_pattern.findall(text_value):
        parts = value.split(".")

        if all(
            0 <= int(part) <= 255
            for part in parts
        ):
            if value not in found["ips"]:
                found["ips"].append(value)

    for value in sha256_pattern.findall(text_value):
        value = value.lower()
        if value not in found["hashes"]["sha256"]:
            found["hashes"]["sha256"].append(value)

    for value in sha1_pattern.findall(text_value):
        value = value.lower()

        if value not in found["hashes"]["sha1"]:
            found["hashes"]["sha1"].append(value)

    for value in md5_pattern.findall(text_value):
        value = value.lower()

        if value not in found["hashes"]["md5"]:
            found["hashes"]["md5"].append(value)

    for value in domain_pattern.findall(text_value):
        if value in found["ips"]:
            continue

        if value.lower() in {
            item.lower()
            for item in found["emails"]
        }:
            continue

        if value not in found["domains"]:
            found["domains"].append(value)

    return found


def _engine_result_to_iocs(result):
    """
    Normalize common IOC-engine output shapes into one structure.
    """
    empty = {
        "urls": [],
        "domains": [],
        "ips": [],
        "emails": [],
        "hashes": {
            "md5": [],
            "sha1": [],
            "sha256": []
        }
    }

    if not isinstance(result, dict):
        return empty

    source = result.get("iocs")

    if isinstance(source, dict):
        result = source

    urls = (
        result.get("urls")
        or result.get("URLS")
        or result.get("url")
        or []
    )

    domains = (
        result.get("domains")
        or result.get("DOMAIN")
        or []
    )

    ips = (
        result.get("ips")
        or result.get("IP")
        or []
    )

    emails = (
        result.get("emails")
        or result.get("EMAILS")
        or result.get("email")
        or []
    )

    hashes = (
        result.get("hashes")
        or result.get("HASHES")
        or {}
    )

    if not isinstance(hashes, dict):
        hashes = {}

    empty["urls"] = _clean_ioc_values(urls)
    empty["domains"] = _clean_ioc_values(domains)
    empty["ips"] = _clean_ioc_values(ips)
    empty["emails"] = _clean_ioc_values(emails)

    empty["hashes"]["md5"] = _clean_ioc_values(
        hashes.get("md5")
        or hashes.get("MD5")
    )

    empty["hashes"]["sha1"] = _clean_ioc_values(
        hashes.get("sha1")
        or hashes.get("SHA1")
        or hashes.get("sha-1")
    )

    empty["hashes"]["sha256"] = _clean_ioc_values(
        hashes.get("sha256")
        or hashes.get("SHA256")
        or hashes.get("sha-256")
    )

    return empty


def _extract_iocs(text_value):
    """
    Use the dedicated IOC engine when one of its common public
    interfaces is available. Otherwise use the safe local fallback.
    """
    fallback = _fallback_extract_iocs(
        text_value
    )

    if _ioc_engine_module is None:
        return fallback

    candidates = []

    for function_name in (
        "extract_iocs",
        "extract_all_iocs",
        "parse_iocs",
        "analyze_iocs",
        "extract",
        "analyze",
    ):
        function = getattr(
            _ioc_engine_module,
            function_name,
            None
        )

        if callable(function):
            candidates.append(function)

    for function in candidates:
        try:
            result = function(
                text_value
            )

            normalized = _engine_result_to_iocs(
                result
            )

            if any([
                normalized["urls"],
                normalized["domains"],
                normalized["ips"],
                normalized["emails"],
                normalized["hashes"]["md5"],
                normalized["hashes"]["sha1"],
                normalized["hashes"]["sha256"],
            ]):
                return normalized

        except Exception:
            continue

    return fallback


def _collect_ioc_source_text(
    url_result=None,
    file_result=None,
    email_result=None
):
    """
    Convert detector outputs into text that can be processed by
    the IOC engine.
    """
    parts = []

    for result in (
        url_result,
        file_result,
        email_result
    ):
        if result is None:
            continue

        if isinstance(result, str):
            parts.append(result)

        elif isinstance(result, dict):
            try:
                parts.append(
                    json.dumps(
                        result,
                        ensure_ascii=False
                    )
                )
            except Exception:
                parts.append(
                    str(result)
                )

        else:
            parts.append(
                str(result)
            )

    return "\n".join(parts)


def _ioc_items_from_results(
    url_result=None,
    file_result=None,
    email_result=None
):
    """
    Extract IOCs from detector results.
    Also explicitly adds detector-provided URLs and hashes so
    structured detector outputs are not lost.
    """
    source_text = _collect_ioc_source_text(
        url_result=url_result,
        file_result=file_result,
        email_result=email_result
    )

    extracted = _extract_iocs(
        source_text
    )

    items = []

    def add_item(
        ioc_type,
        value,
        confidence,
        source
    ):
        value = str(value or "").strip()

        if not value:
            return

        normalized_type = _normalize_ioc_type(
            ioc_type
        )

        key = (
            normalized_type,
            value.lower()
        )

        if any(
            item["_key"] == key
            for item in items
        ):
            return

        items.append({
            "_key": key,
            "ioc_type": normalized_type,
            "value": value,
            "confidence": int(
                max(
                    0,
                    min(
                        100,
                        int(confidence)
                    )
                )
            ),
            "source": source
        })

    for value in extracted["urls"]:
        add_item(
            "URL",
            value,
            85,
            "IOC Engine"
        )

    for value in extracted["domains"]:
        add_item(
            "DOMAIN",
            value,
            80,
            "IOC Engine"
        )

    for value in extracted["ips"]:
        add_item(
            "IP",
            value,
            80,
            "IOC Engine"
        )

    for value in extracted["emails"]:
        add_item(
            "EMAIL",
            value,
            75,
            "IOC Engine"
        )

    for value in extracted["hashes"]["md5"]:
        add_item(
            "MD5",
            value,
            90,
            "IOC Engine"
        )

    for value in extracted["hashes"]["sha1"]:
        add_item(
            "SHA1",
            value,
            90,
            "IOC Engine"
        )

    for value in extracted["hashes"]["sha256"]:
        add_item(
            "SHA256",
            value,
            95,
            "IOC Engine"
        )

    # Detector-specific structured values.
    if isinstance(url_result, dict):
        for key in (
            "url",
            "normalized_url",
            "final_url"
        ):
            if url_result.get(key):
                add_item(
                    "URL",
                    url_result.get(key),
                    90,
                    "URL Detector"
                )

        for key in (
            "domain",
            "hostname"
        ):
            if url_result.get(key):
                add_item(
                    "DOMAIN",
                    url_result.get(key),
                    85,
                    "URL Detector"
                )

        for key in (
            "ip",
            "ip_address"
        ):
            if url_result.get(key):
                add_item(
                    "IP",
                    url_result.get(key),
                    85,
                    "URL Detector"
                )

    if isinstance(file_result, dict):
        for key, ioc_type, confidence in (
            ("md5", "MD5", 90),
            ("sha1", "SHA1", 92),
            ("sha256", "SHA256", 95)
        ):
            if file_result.get(key):
                add_item(
                    ioc_type,
                    file_result.get(key),
                    confidence,
                    "File Detector"
                )

    if isinstance(email_result, dict):
        for key in (
            "sender",
            "from",
            "sender_email"
        ):
            if email_result.get(key):
                add_item(
                    "EMAIL",
                    email_result.get(key),
                    85,
                    "Email Detector"
                )

    return items


def _persist_iocs(
    url_result=None,
    file_result=None,
    email_result=None,
    incident_id=None
):
    """
    Store extracted IOCs in the existing IOC database and return
    a complete integration summary.
    """
    items = _ioc_items_from_results(
        url_result=url_result,
        file_result=file_result,
        email_result=email_result
    )

    database_incident_id = (
        _get_latest_database_incident_id(
            incident_id=incident_id
        )
    )

    summary = {
        "enabled": True,
        "incident_id": incident_id,
        "database_incident_id": database_incident_id,
        "extracted_count": len(items),
        "created_count": 0,
        "known_count": 0,
        "records": [],
        "status": "not_stored"
    }

    if database_incident_id is None:
        summary["status"] = (
            "no_incident_record_available"
        )

        return summary

    for item in items:
        try:
            existing = IOC_DATABASE.get_ioc(
                item["ioc_type"],
                item["value"]
            )

            if existing:
                summary["known_count"] += 1

                summary["records"].append({
                    "ioc_type": item["ioc_type"],
                    "value": item["value"],
                    "known": True,
                    "created": False,
                    "ioc": existing
                })

                continue

            result = IOC_DATABASE.add_ioc(
                ioc_type=item["ioc_type"],
                incident_id=database_incident_id,
                value=item["value"],
                confidence=item["confidence"],
                source=item["source"]
            )

            created = bool(
                isinstance(result, dict)
                and result.get("created")
            )

            if created:
                summary["created_count"] += 1

            summary["records"].append({
                "ioc_type": item["ioc_type"],
                "value": item["value"],
                "known": False,
                "created": created,
                "ioc": (
                    result.get("ioc")
                    if isinstance(result, dict)
                    else None
                )
            })

        except Exception as error:
            summary["records"].append({
                "ioc_type": item["ioc_type"],
                "value": item["value"],
                "known": False,
                "created": False,
                "error": str(error)
            })

    summary["status"] = "stored"

    return summary




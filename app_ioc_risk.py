def _ioc_risk_weight(ioc_type):
    """
    Base threat-intelligence weight for a known IOC type.
    """
    weights = {
        "URL": 90,
        "DOMAIN": 85,
        "IP": 82,
        "EMAIL": 70,
        "MD5": 88,
        "SHA1": 92,
        "SHA256": 95,
    }
    return weights.get(
        _normalize_ioc_type(ioc_type),
        70
    )


def _calculate_ioc_risk_intelligence(ioc_summary):
    """
    Convert IOC database matches and confidence into a normalized
    threat-intelligence contribution.

    This layer does not replace the existing Risk Engine. It adds
    an explicit IOC intelligence signal that can be consumed by
    the incident/correlation pipeline.
    """
    if not isinstance(ioc_summary, dict):
        return {
            "enabled": True,
            "matched_count": 0,
            "average_confidence": 0,
            "threat_intelligence_score": 0,
            "risk_bonus": 0,
            "risk_level": "LOW",
            "signals": [],
        }

    records = ioc_summary.get("records") or []

    matched = []
    for record in records:
        if not isinstance(record, dict):
            continue

        ioc = record.get("ioc") or {}
        known = bool(record.get("known"))

        if not known or not isinstance(ioc, dict):
            continue

        confidence = ioc.get("confidence", 0)
        try:
            confidence = max(0, min(100, int(confidence)))
        except (TypeError, ValueError):
            confidence = 0

        ioc_type = _normalize_ioc_type(
            record.get("ioc_type") or ioc.get("ioc_type")
        )

        weight = _ioc_risk_weight(ioc_type)

        # Confidence and IOC-type criticality are combined.
        intelligence_score = round(
            (confidence * 0.7) + (weight * 0.3)
        )

        matched.append({
            "ioc_type": ioc_type,
            "value": record.get("value") or ioc.get("value"),
            "confidence": confidence,
            "type_weight": weight,
            "intelligence_score": intelligence_score,
            "source": ioc.get("source"),
        })

    if not matched:
        return {
            "enabled": True,
            "matched_count": 0,
            "average_confidence": 0,
            "threat_intelligence_score": 0,
            "risk_bonus": 0,
            "risk_level": "LOW",
            "signals": [],
        }

    average_confidence = round(
        sum(item["confidence"] for item in matched)
        / len(matched)
    )

    threat_intelligence_score = round(
        sum(item["intelligence_score"] for item in matched)
        / len(matched)
    )

    # Multiple known IOCs increase the correlation contribution,
    # while keeping the bonus bounded.
    risk_bonus = min(
        35,
        round(
            (threat_intelligence_score * 0.20)
            + ((len(matched) - 1) * 5)
        )
    )

    if threat_intelligence_score >= 85:
        risk_level = "CRITICAL"
    elif threat_intelligence_score >= 70:
        risk_level = "HIGH"
    elif threat_intelligence_score >= 40:
        risk_level = "MEDIUM"
    else:
        risk_level = "LOW"

    return {
        "enabled": True,
        "matched_count": len(matched),
        "average_confidence": average_confidence,
        "threat_intelligence_score": threat_intelligence_score,
        "risk_bonus": risk_bonus,
        "risk_level": risk_level,
        "signals": matched,
    }


def _apply_ioc_risk_to_result(
    orchestration_result,
    ioc_intelligence
):
    """
    Attach IOC intelligence to the existing incident result and
    calculate an IOC-adjusted risk score without destroying the
    original Risk Engine score.
    """
    if not isinstance(orchestration_result, dict):
        return orchestration_result

    if not isinstance(ioc_intelligence, dict):
        return orchestration_result

    unified = orchestration_result.get("unified_risk")
    if not isinstance(unified, dict):
        unified = {}

    original_score = unified.get("overall_score", 0)
    pipeline_unified = None

    # The Agent Orchestrator stores the deterministic incident
    # pipeline result under agent_results.incident_pipeline.
    agent_results = orchestration_result.get("agent_results")
    if isinstance(agent_results, dict):
        incident_pipeline = agent_results.get("incident_pipeline")
        if isinstance(incident_pipeline, dict):
            nested_unified = incident_pipeline.get("unified_risk")
            if isinstance(nested_unified, dict):
                pipeline_unified = nested_unified
                try:
                    if int(original_score or 0) <= 0:
                        original_score = nested_unified.get("overall_score", 0)
                except (TypeError, ValueError):
                    original_score = nested_unified.get("overall_score", 0)

    # Compatibility fallback for older orchestration structures.
    if pipeline_unified is None:
        incident_pipeline = orchestration_result.get("incident_pipeline")
        if isinstance(incident_pipeline, dict):
            nested_unified = incident_pipeline.get("unified_risk")
            if isinstance(nested_unified, dict):
                pipeline_unified = nested_unified
                try:
                    if int(original_score or 0) <= 0:
                        original_score = nested_unified.get("overall_score", 0)
                except (TypeError, ValueError):
                    original_score = nested_unified.get("overall_score", 0)

    try:
        original_score = max(0, min(100, int(original_score)))
    except (TypeError, ValueError):
        original_score = 0

    risk_bonus = ioc_intelligence.get("risk_bonus", 0)
    try:
        risk_bonus = max(0, min(35, int(risk_bonus)))
    except (TypeError, ValueError):
        risk_bonus = 0

    adjusted_score = min(100, original_score + risk_bonus)

    # Keep the project's existing Risk Engine thresholds.
    if adjusted_score >= 70:
        adjusted_level = "CRITICAL"
    elif adjusted_score >= 45:
        adjusted_level = "HIGH"
    elif adjusted_score >= 20:
        adjusted_level = "MEDIUM"
    else:
        adjusted_level = "LOW"

    original_level = None
    if isinstance(pipeline_unified, dict):
        original_level = pipeline_unified.get("overall_level")
    if not original_level:
        original_level = unified.get("overall_level")
    if not original_level:
        if original_score >= 70:
            original_level = "CRITICAL"
        elif original_score >= 45:
            original_level = "HIGH"
        elif original_score >= 20:
            original_level = "MEDIUM"
        else:
            original_level = "LOW"

    unified["original_score"] = original_score
    unified["ioc_risk_bonus"] = risk_bonus
    unified["overall_score_before_ioc"] = original_score
    unified["overall_level_before_ioc"] = original_level
    unified["overall_score"] = adjusted_score
    unified["overall_level"] = adjusted_level
    unified["ioc_adjusted"] = True

    orchestration_result["unified_risk"] = unified
    orchestration_result["ioc_intelligence"] = ioc_intelligence

    incident = orchestration_result.get("incident")
    if isinstance(incident, dict):
        incident["risk_score_before_ioc"] = original_score
        incident["incident_level_before_ioc"] = original_level
        incident["ioc_risk_bonus"] = risk_bonus
        incident["risk_score"] = adjusted_score
        incident["incident_level"] = adjusted_level

    # Keep the nested deterministic pipeline result consistent with
    # the final top-level IOC-adjusted result.
    if isinstance(pipeline_unified, dict):
        pipeline_unified["original_score"] = original_score
        pipeline_unified["overall_score_before_ioc"] = original_score
        pipeline_unified["overall_level_before_ioc"] = original_level
        pipeline_unified["ioc_risk_bonus"] = risk_bonus
        pipeline_unified["overall_score"] = adjusted_score
        pipeline_unified["overall_level"] = adjusted_level
        pipeline_unified["ioc_adjusted"] = True

    return orchestration_result


def analyze_file_api():

    if "file" not in request.files:

        return jsonify({

            "success":
                False,

            "error":
                "No file uploaded."

        }), 400

    uploaded_file = (
        request.files["file"]
    )

    if not uploaded_file.filename:

        return jsonify({

            "success":
                False,

            "error":
                "Filename is missing."

        }), 400

    temp_path = None

    try:

        suffix = os.path.splitext(
            uploaded_file.filename
        )[1]

        with tempfile.NamedTemporaryFile(
            delete=False,
            suffix=suffix
        ) as temp_file:

            uploaded_file.save(
                temp_file.name
            )

            temp_path = (
                temp_file.name
            )

        result = analyze_file(
            temp_path
        )

        return jsonify({

            "success":
                True,

            "result":
                result

        })

    except Exception as error:

        return jsonify({

            "success":
                False,

            "error":
                str(error)

        }), 500

    finally:

        if (
            temp_path
            and os.path.exists(
                temp_path
            )
        ):

            try:

                os.remove(
                    temp_path
                )

            except OSError:

                pass


